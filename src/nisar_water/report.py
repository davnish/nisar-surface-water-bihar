"""Turn run outputs into Markdown: per-run results.md, the experiment README results block and INDEX.md."""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from nisar_water import REPO_ROOT

EXP_ROOT = REPO_ROOT / "experiments"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _fmt(v) -> str:
    return f"{v:.4f}" if isinstance(v, float) else str(v)


def results_markdown(run_dir: Path, metrics: dict, link_base: Path | None = None) -> str:
    """link_base: folder the Markdown will live in (figure links are relative to it)."""
    link_base = link_base or run_dir
    lines = [f"Run: `{run_dir.relative_to(REPO_ROOT)}`", ""]
    if headline := metrics.get("headline"):
        lines += [f"**Headline:** {headline['name']} = {_fmt(headline['value'])}", ""]
    scalars = {k: v for k, v in metrics.items() if isinstance(v, (int, float, str)) and k != "headline"}
    if scalars:
        lines += ["| metric | value |", "|---|---|"] + [f"| {k} | {_fmt(v)} |" for k, v in scalars.items()] + [""]
    for name, table in metrics.get("tables", {}).items():
        lines += [f"**{name}**", "", table, ""]
    figs = sorted((run_dir / "figures").glob("*.png"))
    if figs:
        lines += ["Figures:"] + [f"- [{f.name}]({f.relative_to(link_base)})" for f in figs]
    return "\n".join(lines)


def write_run_results(run_dir: Path, metrics: dict) -> Path:
    p = run_dir / "results.md"
    p.write_text(results_markdown(run_dir, metrics) + "\n")
    return p


def latest_run(exp_dir: Path) -> Path | None:
    runs = sorted(d for d in (exp_dir / "runs").glob("*") if (d / "metrics.json").exists()) if (exp_dir / "runs").exists() else []
    return runs[-1] if runs else None


def update_readme(exp_id: str) -> Path:
    exp_dir = EXP_ROOT / exp_id
    run = latest_run(exp_dir)
    if run is None:
        raise FileNotFoundError(f"no completed runs in {exp_dir}")
    readme = exp_dir / "README.md"
    block = f"{START}\n{results_markdown(run, json.loads((run / 'metrics.json').read_text()), exp_dir)}\n{END}"
    text = readme.read_text()
    text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S) if START in text else text + "\n" + block + "\n"
    readme.write_text(text)
    return readme


def _field(text: str, name: str) -> str:
    m = re.search(rf"\*\*{name}:\*\*\s*(.+)", text)
    return re.sub(r"<!--.*?-->", "", m.group(1)).strip() if m else "—"


def update_index() -> Path:
    rows = []
    for exp_dir in sorted(d for d in EXP_ROOT.iterdir() if d.is_dir() and not d.name.startswith("_")):
        cfg_p, readme = exp_dir / "config.yaml", exp_dir / "README.md"
        if not cfg_p.exists():
            continue
        cfg = yaml.safe_load(cfg_p.read_text())
        text = readme.read_text() if readme.exists() else ""
        run = latest_run(exp_dir)
        headline = "—"
        if run:
            h = json.loads((run / "metrics.json").read_text()).get("headline")
            headline = f"{h['name']} = {_fmt(h['value'])}" if h else "—"
        rows.append(f"| [{cfg['id']}]({exp_dir.name}/README.md) | {cfg['question']} | {_field(text, 'Status')} "
                    f"| {headline} | {_field(text, 'Decision')} | {run.name if run else '—'} |")
    out = EXP_ROOT / "INDEX.md"
    out.write_text(
        "# Experiment index\n\nAuto-generated by `uv run nisar-water report <id>` — do not edit by hand. "
        "Status and Decision come from each experiment README.\n\n"
        "| ID | Question | Status | Headline metric | Decision | Latest run |\n|---|---|---|---|---|---|\n"
        + "\n".join(rows) + "\n")
    return out
